# ------------------------------------------------------------------------------
# 7. DIAMOND PATTERN
#     *
#    * *
#   * * *
#  * * * *
# * * * * *
#  * * * *
#   * * *
#    * *
#     *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 7. Diamond Pattern ---")
# Upper half
i = 1
while i <= n:
    print(" " * (n - i) + "* " * i)
    i += 1
# Lower half
i = n - 1
while i >= 1:
    print(" " * (n - i) + "* " * i)
    i -= 1


# ------------------------------------------------------------------------------
# 8. HOLLOW SQUARE BOX
# * * * * *
# *       *
# *       *
# *       *
# * * * * *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 8. Hollow Square Box ---")
i = 1
while i <= n:
    if i == 1 or i == n:
        print("* " * n)
    else:
        print("*" + " " * (2 * n - 3) + "*")
    i += 1


# ------------------------------------------------------------------------------
# 9. HOURGLASS PATTERN
# * * * * *
#  * * * *
#   * * *
#    * *
#     *
#    * *
#   * * *
#  * * * *
# * * * * *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 9. Hourglass Pattern ---")
# Top half (inverted pyramid)
i = n
while i >= 1:
    print(" " * (n - i) + "* " * i)
    i -= 1
# Bottom half (pyramid starting from row 2)
i = 2
while i <= n:
    print(" " * (n - i) + "* " * i)
    i += 1


# ------------------------------------------------------------------------------
# 10. BUTTERFLY PATTERN
# *                 *
# * *             * *
# * * *         * * *
# * * * *     * * * *
# * * * * * * * * * *
# * * * *     * * * *
# * * *         * * *
# * *             * *
# *                 *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 10. Butterfly Pattern ---")
# Upper half
i = 1
while i <= n:
    stars = "* " * i
    spaces = "  " * (2 * (n - i))
    print(stars + spaces + stars)
    i += 1

# Lower half
i = n - 1
while i >= 1:
    stars = "* " * i
    spaces = "  " * (2 * (n - i))
    print(stars + spaces + stars)
    i -= 1