# ==============================================================================
# 10 STAR PATTERN PROGRAMS IN PYTHON (FOR & WHILE LOOPS)
# Change the value of 'n' to increase or decrease the size of any pattern.
# ==============================================================================

# ------------------------------------------------------------------------------
# 1. RIGHT-ANGLED TRIANGLE
# *
# * *
# * * *
# * * * *
# * * * * *
# ------------------------------------------------------------------------------
n = 5
print("--- 1. Right-Angled Triangle ---")
for i in range(1, n + 1):
    print("* " * i)


# ------------------------------------------------------------------------------
# 2. INVERTED RIGHT-ANGLED TRIANGLE
# * * * * *
# * * * *
# * * *
# * *
# *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 2. Inverted Right-Angled Triangle ---")
for i in range(n, 0, -1):
    print("* " * i)


# ------------------------------------------------------------------------------
# 3. MIRRORED RIGHT-ANGLED TRIANGLE (RIGHT-ALIGNED)
#         *
#       * *
#     * * *
#   * * * *
# * * * * *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 3. Mirrored Right-Angled Triangle ---")
for i in range(1, n + 1):
    spaces = "  " * (n - i)
    stars = "* " * i
    print(spaces + stars)


# ------------------------------------------------------------------------------
# 4. INVERTED MIRRORED RIGHT-ANGLED TRIANGLE
# * * * * *
#   * * * *
#     * * *
#       * *
#         *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 4. Inverted Mirrored Triangle ---")
for i in range(n, 0, -1):
    spaces = "  " * (n - i)
    stars = "* " * i
    print(spaces + stars)


# ------------------------------------------------------------------------------
# 5. FULL CENTERED PYRAMID
#     *
#    * *
#   * * *
#  * * * *
# * * * * *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 5. Full Centered Pyramid ---")
for i in range(1, n + 1):
    spaces = " " * (n - i)
    stars = "* " * i
    print(spaces + stars)


# ------------------------------------------------------------------------------
# 6. INVERTED FULL PYRAMID
# * * * * *
#  * * * *
#   * * *
#    * *
#     *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 6. Inverted Full Pyramid ---")
for i in range(n, 0, -1):
    spaces = " " * (n - i)
    stars = "* " * i
    print(spaces + stars)


# ------------------------------------------------------------------------------
# 7. DIAMOND PATTERN
#     *
#    * *
#   * * *
#  * * * *
# * * * * *
#  * * * *
#   * * *
#    * *
#     *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 7. Diamond Pattern ---")
# Upper half
for i in range(1, n + 1):
    print(" " * (n - i) + "* " * i)
# Lower half
for i in range(n - 1, 0, -1):
    print(" " * (n - i) + "* " * i)


# ------------------------------------------------------------------------------
# 8. HOLLOW SQUARE BOX (USING WHILE LOOP)
# * * * * *
# *       *
# *       *
# *       *
# * * * * *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 8. Hollow Square Box ---")
i = 1
while i <= n:
    if i == 1 or i == n:
        print("* " * n)
    else:
        print("*" + " " * (2 * n - 3) + "*")
    i += 1


# ------------------------------------------------------------------------------
# 9. HOURGLASS PATTERN
# * * * * *
#  * * * *
#   * * *
#    * *
#     *
#    * *
#   * * *
#  * * * *
# * * * * *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 9. Hourglass Pattern ---")
# Top half (inverted pyramid)
for i in range(n, 1, -1):
    print(" " * (n - i) + "* " * i)
# Bottom half (pyramid)
for i in range(1, n + 1):
    print(" " * (n - i) + "* " * i)


# ------------------------------------------------------------------------------
# 10. BUTTERFLY PATTERN
# *                 *
# * *             * *
# * * *         * * *
# * * * *     * * * *
# * * * * * * * * * *
# * * * *     * * * *
# * * *         * * *
# * *             * *
# *                 *
# ------------------------------------------------------------------------------
n = 5
print("\n--- 10. Butterfly Pattern ---")
# Upper half
for i in range(1, n + 1):
    stars = "* " * i
    spaces = "  " * (2 * (n - i))
    print(stars + spaces + stars)

# Lower half
for i in range(n - 1, 0, -1):
    stars = "* " * i
    spaces = "  " * (2 * (n - i))
    print(stars + spaces + stars)